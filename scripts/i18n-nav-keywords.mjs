#!/usr/bin/env node
/**
 * Build the command-palette keyword index for navigation labels.
 *
 * Every nav item is searchable by its label in every locale with a stored
 * dictionary, plus Japanese romaji readings so a user can match the page while
 * an IME is still composing. The index is generated straight from the dictionary
 * files, so adding a locale automatically adds its nav labels here.
 *
 * Run after any locale dictionary changes:
 *   node scripts/i18n-nav-keywords.mjs
 *
 * A unit test (tests/unit/i18n-guards.test.ts) asserts the generated index
 * still matches the locale dictionaries, so drift fails CI.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const DICTIONARY = path.join(ROOT, "src/lib/i18n/dictionary.ts");
const NAVIGATION = path.join(ROOT, "src/components/layout/navigation.ts");
const LOCALES_DIR = path.join(ROOT, "src/lib/i18n/locales");
const OUT = path.join(ROOT, "src/lib/i18n/nav-search-keywords.ts");

// Every code with a stored dictionary; en is the English source itself.
const STORED = [
  "en",
  "ja", "es", "es-MX", "fr", "de", "pt", "it", "nl", "zh", "ko", "hi", "ru",
  "pl", "cs", "uk", "bg", "tr", "sv", "no", "fi", "da", "el", "ro", "hr",
  "et", "th", "vi", "id", "bn", "mn", "kk", "ky", "fil",
  "ar", "ur", "fa", "he",
];

// Hepburn-style readings of the Japanese nav labels. These are not
// translations — they let an IME composition match before conversion.
const ROMAJI = {
  "nav.dashboard": ["dasshuboodo", "dasshubōdo", "dabādo"],
  "nav.areas": ["eria"],
  "nav.goals": ["mokuhyou", "mokuhyō"],
  "nav.projects": ["purojekuto"],
  "nav.tasks": ["tasuku"],
  "nav.notes": ["nooto", "nōto"],
  "nav.resources": ["risoosu", "risōsu"],
  "nav.topics": ["topikku"],
  "nav.contacts": ["renrakusaki", "renrakusen"],
  "nav.myDay": ["maidei", "mai dei"],
  "nav.inbox": ["jushintorei", "jushin"],
  "nav.knowledgeHub": ["narejjihabu", "chishikihabu"],
  "nav.settings": ["settei"],
  "nav.pioneers": ["paionia"],
  "nav.support": ["sapooto", "sapōto"],
  "nav.reportBug": ["fuguai", "fuguaiwowokoku"],
  "legal.terms": ["riyoukiyaku", "riyōkiyaku"],
  "legal.privacy": ["puraibashii", "puraibashī"],
  "legal.security": ["sekyuriti", "sekiryuti"],
  "legal.subprocessors": ["saiitakusaki"],
  "legal.dataAndAi": ["deetatoai", "dētatoai"],
  "legal.responsibleDisclosure": ["sekininiarukaiji", "sekininiaru"],
};

const ENTRY = /^  "([^"]+)": ("(?:[^"\\]|\\.)*"),?$/gm;

function parseEntries(source) {
  const out = {};
  let match;
  while ((match = ENTRY.exec(source))) out[match[1]] = JSON.parse(match[2]);
  return out;
}

const english = parseEntries(await readFile(DICTIONARY, "utf8"));
const navigation = await readFile(NAVIGATION, "utf8");
// Only actual navigation labels — legal *body* keys are not searchable pages.
// The four extras are searchable labels rendered outside navigation.ts.
const EXTRA_LABEL_KEYS = ["nav.pioneers", "nav.reportBug", "nav.settings", "nav.support"];
const navKeys = Array.from(
  new Set([
    ...[...navigation.matchAll(/labelKey:\s*"([^"]+)"/g)].map((match) => match[1]),
    ...EXTRA_LABEL_KEYS,
  ]),
).sort();

const dictionaries = { en: english };
for (const code of STORED) {
  if (code === "en") continue;
  dictionaries[code] = parseEntries(await readFile(path.join(LOCALES_DIR, `${code}.ts`), "utf8"));
}

const entries = navKeys.map((key) => {
  const translations = STORED.map((code) => dictionaries[code]?.[key]).filter(
    (value) => typeof value === "string" && value.length > 0,
  );
  const keywords = Array.from(
    new Set([...translations, ...(ROMAJI[key] ?? [])].map((value) => value.trim())),
  );
  return `  ${JSON.stringify(key)}: [\n${keywords
    .map((value) => `    ${JSON.stringify(value)},`)
    .join("\n")}\n  ],`;
});

const output = `// Generated by scripts/i18n-nav-keywords.mjs — do not hand-edit.
//
// Command-palette keywords for nav items: the label in every stored locale,
// plus Japanese romaji readings so an in-progress IME composition matches
// before conversion. Kept separate from the locale dictionaries so the palette
// can match every language without shipping every dictionary.

export const NAV_SEARCH_KEYWORDS: Record<string, readonly string[]> = {
${entries.join("\n")}
};

export function navSearchKeywords(labelKey: string): readonly string[] {
  return NAV_SEARCH_KEYWORDS[labelKey] ?? [];
}
`;

await writeFile(OUT, output);
console.log(`Wrote ${navKeys.length} nav keyword entries to src/lib/i18n/nav-search-keywords.ts`);
