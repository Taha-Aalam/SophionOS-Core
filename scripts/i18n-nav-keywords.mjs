#!/usr/bin/env node
/**
 * Build the command-palette keyword index for navigation labels.
 *
 * Every nav item is searchable by its label in all stored Tier-1 locales, plus
 * Japanese romaji readings so a user can match the page while an IME is still
 * composing (hiragana/romaji before conversion to タスク).
 *
 * Run after the seed or the Tier-1 locale files change:
 *   node scripts/i18n-nav-keywords.mjs
 *
 * A unit test (tests/unit/i18n-guards.test.ts) asserts the generated index
 * still matches the locale dictionaries, so drift fails CI.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const SEED = path.join(ROOT, "docs/languages/ui-dictionary.seed.json");
const OUT = path.join(ROOT, "src/lib/i18n/nav-search-keywords.ts");

const TIER1 = ["en", "ja", "es", "es-MX", "fr", "de", "pt", "it", "nl", "zh", "ko", "hi", "ru"];

// Hepburn-style readings of the Japanese nav labels. These are not
// translations — they let an IME composition match before conversion.
const ROMAJI = {
  "nav.dashboard": ["dasshuboodo", "dasshubōdo", "dabādo"],
  "nav.areas": ["eria"],
  "nav.goals": ["mokuhyou", "mokuhyō"],
  "nav.projects": ["purojekuto"],
  "nav.tasks": ["tasuku"],
  "nav.notes": ["nooto", "nōto"],
  "nav.resources": ["risoosu", "risōsu"],
  "nav.topics": ["topikku"],
  "nav.contacts": ["renrakusaki", "renrakusen"],
  "nav.myDay": ["maidei", "mai dei"],
  "nav.inbox": ["jushintorei", "jushin"],
  "nav.knowledgeHub": ["narejjihabu", "chishikihabu"],
  "nav.settings": ["settei"],
  "nav.pioneers": ["paionia"],
  "nav.support": ["sapooto", "sapōto"],
  "nav.reportBug": ["fuguai", "fuguaiwowokoku"],
  "legal.terms": ["riyoukiyaku", "riyōkiyaku"],
  "legal.privacy": ["puraibashii", "puraibashī"],
  "legal.security": ["sekyuriti", "sekiryuti"],
  "legal.subprocessors": ["saiitakusaki"],
  "legal.dataAndAi": ["deetatoai", "dētatoai"],
  "legal.responsibleDisclosure": ["sekininiarukaiji", "sekininiaru"],
};

const seed = JSON.parse(await readFile(SEED, "utf8"));
const navKeys = Object.keys(seed.strings)
  .filter((key) => key.startsWith("nav.") || key.startsWith("legal."))
  .sort();

const entries = navKeys.map((key) => {
  const translations = TIER1.map((code) => seed.strings[key]?.[code]).filter(
    (value) => typeof value === "string" && value.length > 0,
  );
  const keywords = Array.from(
    new Set([...translations, ...(ROMAJI[key] ?? [])].map((value) => value.trim())),
  );
  return `  ${JSON.stringify(key)}: [\n${keywords
    .map((value) => `    ${JSON.stringify(value)},`)
    .join("\n")}\n  ],`;
});

const output = `// Generated by scripts/i18n-nav-keywords.mjs — do not hand-edit.
//
// Command-palette keywords for nav items: the label in every stored Tier-1
// locale, plus Japanese romaji readings so an in-progress IME composition
// matches before conversion. Kept separate from the locale dictionaries so the
// palette can match every language without shipping every dictionary.

export const NAV_SEARCH_KEYWORDS: Record<string, readonly string[]> = {
${entries.join("\n")}
};

export function navSearchKeywords(labelKey: string): readonly string[] {
  return NAV_SEARCH_KEYWORDS[labelKey] ?? [];
}
`;

await writeFile(OUT, output);
console.log(`Wrote ${navKeys.length} nav keyword entries to src/lib/i18n/nav-search-keywords.ts`);
